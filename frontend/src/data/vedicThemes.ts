export const getDailyVedicTheme = (): VedicTheme => {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = Math.abs(dayOfYear) % VEDIC_THEMES.length;
  return VEDIC_THEMES[index];
};

export const getVedicThemeById = (id: string): VedicTheme => {
  return VEDIC_THEMES.find((t) => t.id === id) || VEDIC_THEMES[0];
};
